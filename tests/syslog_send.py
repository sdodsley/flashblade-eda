"""Send representative FlashBlade syslog lines to the purefb_syslog listener.

    python3 tests/syslog_send.py <host> <port> [udp|tcp] [array-name] [storm]

The management lines follow the layouts the FlashBlade Admin Guide
documents (purity.alert with #012-separated details, purity.audit as
Key=value pairs, purity.test); the data-audit records follow the
file-auditing guide's JSON schema (pf fb) and the same schema as a
FlashArray fileaudit line (pf fa). With `storm` as the fifth argument, 60
extension-changing renames and 120 deletes from one user follow, enough
to raise purefb_file_activity twice at the default thresholds. verify:
the hostname and timestamp the lab array really logs; these lines are
representative, not captured.
"""

import json
import socket
import sys
import time

host = sys.argv[1] if len(sys.argv) > 1 else "127.0.0.1"
port = int(sys.argv[2]) if len(sys.argv) > 2 else 5140
proto = sys.argv[3] if len(sys.argv) > 3 else "udp"
array = sys.argv[4] if len(sys.argv) > 4 else "fb-a"
storm = len(sys.argv) > 5 and sys.argv[5] == "storm"
stamp = time.strftime("%b %d %H:%M:%S")
utc = time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime())
iso = time.strftime("%Y-%m-%dT%H:%M:%S.000Z", time.gmtime())
array_id = "1f3a9c2e-5b7d-4e81-9a6c-0d2f4b6e8a10"


def alert(level, state, subject, code, text, action):
    details = "#012".join(
        [
            text,
            f"Severity: {level.capitalize()}",
            f"State: {state}",
            f"First Seen UTC Time: {utc}",
            f"Array Name: {array}",
            f"Array ID: {array_id}",
            "Purity//FB Version: 4.6.4",
            f"Suggested Action: {action}",
            f"Knowledge Base Article: https://support.purestorage.com/?cid=Alert_{code}",
        ]
    )
    return (
        f"{stamp} {array}-fm1 purity.alert: {level.upper()} {state} - {array}: "
        f"{subject} [{code}] #012{details}"
    )


def audit(n, user, location, ui, command, subcommand, arguments):
    return (
        f"{stamp} {array}-fm1 purity.audit: - Adding audit entry. "
        f"GUID=139a249a-7c1f-4d86-8fe8-2108b63e4f{n:02x}, ID={6683 + n}, "
        f"Time={utc}.000000, User={user}, Location={location}, UI={ui}, "
        f"Command={command}, Subcommand={subcommand}, Arguments={arguments}"
    )


def record(pf="fb", **over):
    rec = {
        "pf": pf,
        "v": "1.3",
        "eid": 1001,
        "time": iso,
        "u_sid": "S-1-5-21-1111111111-2222222222-3333333333-1105",
        "user": "EXAMPLE\\alice",
        "client_ip": "10.9.228.192",
        "proto": "smb",
        "inode": 42,
        "fs": "smb-fs2",
        "path": "New folder\\file.txt",
        "op_code": 6,
        "op_name": "create_regular_file",
        "f_type": "reg",
        "result": "success",
        "create_disposition": "create",
    }
    rec.update(over)
    return f"<134>{stamp} {array} : " + json.dumps(rec)


lines = [
    alert(
        "critical",
        "Open",
        "Blade CH1.FB3 is unhealthy",
        1000,
        "Blade CH1.FB3 is unhealthy and has been taken out of service.",
        "Contact Pure Storage Support.",
    ),
    alert(
        "warning",
        "Open",
        "Message Drop for Remote Syslog (Audit Related)",
        1139,
        "Data-audit messages to syslog server syslog1 were dropped.",
        "Check the syslog server and the network path.",
    ),
    alert(
        "info",
        "Closed",
        "Message Drop for Remote Syslog (Audit Related)",
        1139,
        "The syslog server is reachable again.",
        "None.",
    ),
    audit(
        0,
        "pureuser",
        "192.0.2.12",
        "REST",
        "purepolicy",
        "nfs delete",
        "cnfs-fixer-pol",
    ),
    audit(
        1, "eda-human", "203.0.113.9", "GUI", "purefs", "setattr", "--size 2T eda-demo"
    ),
    f"{stamp} {array}-fm1 purity.test: This is a test message generated by Pure "
    f"Storage FlashBlade. UTC Time: {utc} Array Name: {array}",
    record(),
    record(
        op_name="rename",
        path="New folder\\file.txt",
        tgt_path="New folder\\file.txt.locked",
    ),
    record(
        "fa", fs="fa-fs1", proto="nfs", user="alice", path="/dir/file.txt", eid=2001
    ),
]
if storm:
    for i in range(60):
        lines.append(
            record(
                op_name="rename",
                path=f"docs\\report{i}.docx",
                tgt_path=f"docs\\report{i}.docx.locked",
                eid=3000 + i,
            )
        )
    for i in range(120):
        lines.append(record(op_name="unlink", path=f"docs\\old{i}.txt", eid=4000 + i))

if proto == "tcp":
    s = socket.create_connection((host, port))
    for line in lines:
        s.sendall((line + "\n").encode())
    s.close()
else:
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    for line in lines:
        s.sendto(line.encode(), (host, port))
    s.close()
print(f"sent {len(lines)} lines to {host}:{port}/{proto}")
