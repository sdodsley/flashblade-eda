# --- tcp client plumbing ---------------------------------------------------
class FakeReader:
    def __init__(self, items):
        self.items = list(items)

    def at_eof(self):
        return not self.items

    async def readline(self):
        item = self.items.pop(0)
        if isinstance(item, Exception):
            raise item
        return item


class FakeWriter:
    def __init__(self, peer):
        self.peer = peer
        self.closed = False
        self.waited = False

    def get_extra_info(self, name):
        return self.peer

    def close(self):
        self.closed = True

    async def wait_closed(self):
        self.waited = True


def test_tcp_client_emits_lines_and_closes_on_an_over_long_line(syslog):
    got = []
    reader = FakeReader(
        [f"{TEST}\n".encode(), b"\n", ValueError("too long"), b"never\n"]
    )
    writer = FakeWriter(("198.51.100.9", 40000))
    asyncio.run(
        syslog._tcp_client(
            reader, writer, lambda l, s, p: got.append((l.strip(), s, p)), []
        )
    )
    assert got == [(TEST, "198.51.100.9", "tcp")]
    assert writer.closed and writer.waited
    assert reader.items == [b"never\n"]  # the connection was dropped, not drained


def test_tcp_client_accepts_a_100_kb_data_audit_record(syslog):
    """A real asyncio StreamReader with the plugin's limit, fed a 100 KB
    record: the whole line arrives as one file event and the connection
    stays open for the next line. A line over 128 KB still closes it."""
    assert syslog.TCP_LINE_LIMIT >= 131072
    big = _record(path="deep\\" + "x" * (100 * 1024))
    line = ("<134>Nov 12 10:10:00 fb-a : " + json.dumps(big) + "\n").encode()
    assert 100 * 1024 < len(line) < syslog.TCP_LINE_LIMIT
    got = []

    async def go(payload):
        reader = asyncio.StreamReader(limit=syslog.TCP_LINE_LIMIT)
        reader.feed_data(payload)
        reader.feed_eof()
        writer = FakeWriter(("10.21.200.230", 40000))
        await syslog._tcp_client(
            reader,
            writer,
            lambda l, s, p: got.append(syslog.parse(l, {}, set())),
            [],
        )
        return writer

    writer = asyncio.run(go(line + f"{TEST}\n".encode()))
    assert writer.closed and [e["kind"] for e in got] == ["file", "test"]
    assert got[0]["path"] == big["path"] and len(got[0]["path"]) > 100 * 1024
    got.clear()
    huge = (
        "<134>Nov 12 10:10:00 fb-a : " + json.dumps(_record(path="y" * 140000)) + "\n"
    ).encode()
    asyncio.run(go(huge + f"{TEST}\n".encode()))
    assert got == []  # dropped at the limit, the rest never read


def test_tcp_client_refuses_a_peer_outside_allowed_sources(syslog):
    got = []
    reader = FakeReader([f"{TEST}\n".encode()])
    writer = FakeWriter(("192.0.2.1", 40000))
