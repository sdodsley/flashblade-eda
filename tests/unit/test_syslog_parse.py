def test_documentation_block_covers_every_argument_and_event(syslog):
    import pathlib
    import re

    doc = yaml.safe_load(syslog.DOCUMENTATION)
    assert doc["name"] == "purefb_syslog"
    options = set(doc["options"])
    source = pathlib.Path(syslog.__file__).read_text()
    read = set(re.findall(r'args\.get\(\s*"([a-z_]+)"', source))
    assert read <= options, f"undocumented arguments: {sorted(read - options)}"
    for name in (
        "allowed_sources",
        "programs",
        "hostnames",
        "file_window_seconds",
        "mass_delete_threshold",
        "rename_storm_threshold",
    ):
        assert name in options, name
    docstring = syslog.__doc__
    for name in list(syslog.EVENT_NAMES.values()) + ["purefb_file_activity"]:
        assert name in docstring and name in syslog.DOCUMENTATION, name
    examples = yaml.safe_load(syslog.EXAMPLES)
    assert examples[0]["sources"][0]["sdodsley.flashblade_eda.purefb_syslog"]
    assert "purefa" not in source


# --- sliding windows ---------------------------------------------------------
def _stamp(seconds):
    return f"2026-11-12T10:{seconds // 60:02d}:{seconds % 60:02d}.000Z"


def test_rename_storm_raises_one_activity_event_per_window(syslog):
    w = syslog.ActivityWindows(60, 100, 50)
    got = []
    for i in range(49):
        got.append(
            w.observe(
                _record(
                    time=_stamp(i),
                    op_name="rename",
                    path=f"docs\\report{i}.docx",
                    tgt_path=f"docs\\report{i}.docx.locked",
                )
            )
        )
    assert all(g is None for g in got)
    act = w.observe(
        _record(
            time=_stamp(49),
            op_name="rename",
            path="docs\\last.xlsx",
            tgt_path="docs\\last.xlsx.locked",
        )
    )
    assert act is not None
    assert act["rename_storm"] is True and act["mass_delete"] is False
    assert act["renames"] == 50 and act["deletes"] == 0 and act["events"] == 50
    assert act["fs"] == "smb-fs2" and act["user"] == "EXAMPLE\\alice"
    assert act["client_ip"] == "10.9.228.192" and act["proto"] == "smb"
    assert act["window_seconds"] == 60 and act["rename_storm_threshold"] == 50
    assert act["first_time"] == _stamp(0) and act["last_time"] == _stamp(49)
    assert (
        act["sample_paths"][-1] == "docs\\last.xlsx" and len(act["sample_paths"]) == 5
    )
    # the storm goes on: nothing more until a whole window has passed
    for i in range(50, 100):
        assert (
            w.observe(
                _record(
                    time=_stamp(i),
                    op_name="rename",
                    path=f"a{i}.txt",
                    tgt_path=f"a{i}.enc",
                )
            )
            is None
        )
    again = w.observe(
        _record(time=_stamp(110), op_name="rename", path="b.txt", tgt_path="b.enc")
    )
    assert again is not None and again["renames"] >= 50
    # a rename that keeps the extension is a move, not a storm signal
    w2 = syslog.ActivityWindows(60, 100, 2)
    assert (
        w2.observe(_record(op_name="rename", path="a\\x.txt", tgt_path="b\\x.txt"))
        is None
    )
    assert (
        w2.observe(_record(op_name="rename", path="a\\y.txt", tgt_path="b\\y.TXT"))
        is None
    )
    assert w2.observe(_record(op_name="rename", path="z.txt", tgt_path="z")) is None
    assert w2.observe(_record(op_name="rename", path="q.txt", tgt_path="q.bak"))


def test_mass_delete_and_create_delete_pairs(syslog):
    w = syslog.ActivityWindows(60, 100, 50)
    for i in range(99):
        assert (
            w.observe(_record(time=_stamp(i // 2), op_name="unlink", path=f"f{i}"))
            is None
        )
    act = w.observe(_record(time=_stamp(49), op_name="unlink", path="f99"))
    assert act["mass_delete"] is True and act["deletes"] == 100
    assert act["create_delete_pairs"] == 0 and act["rename_storm"] is False
    # the dropper pattern: a small threshold, create then delete the same path
    w = syslog.ActivityWindows(60, 3, 50)
    for i in range(3):
        assert w.observe(_record(op_name="create_regular_file", path=f"tmp{i}")) is None
    assert w.observe(_record(op_name="unlink", path="tmp0")) is None
    assert w.observe(_record(op_name="unlink", path="tmp1")) is None
    act = w.observe(_record(op_name="unlink", path="tmp2"))
    assert act["create_delete_pairs"] == 3 and act["deletes"] == 3
    assert act["mass_delete"] is True and act["events"] == 6
    # a rename storm that turns into a mass delete inside one window is two
    # events, the second carrying both flags; a third threshold crossing of
    # the same kinds stays quiet
    w = syslog.ActivityWindows(60, 2, 2)
    assert (
        w.observe(_record(time=_stamp(0), op_name="rename", path="a.x", tgt_path="a.y"))
        is None
    )
    first = w.observe(
        _record(time=_stamp(1), op_name="rename", path="b.x", tgt_path="b.y")
    )
    assert first["rename_storm"] is True and first["mass_delete"] is False
    assert w.observe(_record(time=_stamp(2), op_name="unlink", path="c")) is None
    second = w.observe(_record(time=_stamp(3), op_name="unlink", path="d"))
    assert second["mass_delete"] is True and second["rename_storm"] is True
    assert w.observe(_record(time=_stamp(4), op_name="unlink", path="e")) is None
    assert (
        w.observe(_record(time=_stamp(5), op_name="rename", path="f.x", tgt_path="f.y"))
        is None
    )


def test_windows_are_per_fs_user_and_client_and_slide(syslog):
    w = syslog.ActivityWindows(60, 2, 50)
    assert w.observe(_record(time=_stamp(0), op_name="unlink", path="a")) is None
    # another user on the same file system does not add to alice's count
    assert (
        w.observe(_record(time=_stamp(1), op_name="unlink", path="b", user="bob"))
        is None
    )
    assert (
        w.observe(_record(time=_stamp(1), op_name="unlink", path="b", fs="other"))
        is None
    )
    assert (
        w.observe(
            _record(time=_stamp(1), op_name="unlink", path="b", client_ip="10.0.0.9")
        )
        is None
    )
    # 61 s later the first delete has left the window
    assert w.observe(_record(time=_stamp(61), op_name="unlink", path="c")) is None
    assert w.observe(_record(time=_stamp(62), op_name="unlink", path="d"))
    # unreadable times are placed at arrival
    assert syslog._epoch("not a time") is None and syslog._epoch(None) is None
    assert syslog._epoch("2026-11-12T10:00:00Z") == syslog._epoch(
        "2026-11-12T10:00:00+00:00"
    )
    assert w.observe(_record(time="garbage", op_name="read", path="e")) is None
    assert syslog._op_kind("create_regular_file") == "create"
    assert syslog._op_kind("rmdir") == "delete" and syslog._op_kind("rename") == (
        "rename"
    )
    assert syslog._op_kind("read") == "other" and syslog._op_kind(None) == "other"
    assert syslog._extension("a\\b\\c.TXT") == "txt" and syslog._extension("/x/y") == ""
    assert syslog._extension(".hidden") == "" and syslog._extension(None) == ""


def test_emitter_tallies_file_events_into_activity(syslog):
    async def go():
        local = asyncio.Queue()
        windows = syslog.ActivityWindows(60, 2, 50)
        emit = syslog._emitter(local, {"fb-a": "inventory-a"}, set(), [], None, windows)
        for i in range(2):
            line = "<134>Nov 12 10:10:00 fb-a : " + json.dumps(
                _record(time=_stamp(i), op_name="unlink", path=f"f{i}")
            )
            assert emit(line, "10.21.200.230", "tcp") is True
        assert local.qsize() == 3
        names = [list(local.get_nowait()) for _ in range(3)]
        assert names == [
            ["purefb_file_event"],
            ["purefb_file_event"],
            ["purefb_file_activity"],
        ]

    asyncio.run(go())

    async def one_activity_record():
        local = asyncio.Queue()
        emit = syslog._emitter(
            local,
            {"fb-a": "inventory-a"},
            set(),
            [],
            None,
            syslog.ActivityWindows(60, 1),
        )
        line = "<134>Nov 12 10:10:00 fb-a : " + json.dumps(
            _record(op_name="unlink", path="f")
        )
