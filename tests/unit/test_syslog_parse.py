def _record(pf="fb", **over):
    rec = {
        "pf": pf,
        "v": "1.3",
        "eid": 1001,
        "time": "2026-11-12T10:10:00.475Z",
        "u_sid": "S-1-5-21-1111111111-2222222222-3333333333-1105",
        "user": "EXAMPLE\\alice",
        "client_ip": "10.9.228.192",
        "proto": "smb",
        "inode": 42,
        "fs": "smb-fs2",
        "path": "New folder\\file.txt",
        "op_code": 6,
        "op_name": "create_regular_file",
        "f_type": "reg",
        "result": "success",
        "create_disposition": "create",
    }
    rec.update(over)
    return rec


# a data-audit record as the file-auditing guide shows it: RFC 3164 header
# `<PRI>DATE ARRAY_NAME : MESSAGE`, no program
FILE_FB = "<134>Nov 12 10:10:00 fb-a : " + json.dumps(_record())
# FlashArray writes the same schema under its fileaudit program
FILE_FA = "<134>Nov 12 10:10:00 array-a fileaudit[4242]: " + json.dumps(
    _record("fa", fs="fa-fs1", path="/dir/file.txt", proto="nfs", user="alice")
)


def test_alert_1000_fields(syslog):
    e = syslog.parse(ALERT_1000, {}, set())
    assert e["kind"] == "alert" and syslog.event_name(e) == "purefb_syslog_alert"
    assert e["array"] == "fb-a" and e["host"] == "fb-a-fm1"
    assert e["program"] == "purity.alert" and e["time"] == "Nov 12 10:00:00"
    assert e["severity"] == "critical" and e["state"] == "open"
    assert e["code"] == 1000 and e["subject"] == "Blade CH1.FB3 is unhealthy"
    assert (
        e["details"] == "Blade CH1.FB3 is unhealthy and has been taken out of service."
    )
    assert e["action"] == "Contact Pure Storage Support."
    assert e["knowledge_base_url"] == "https://support.purestorage.com/?cid=Alert_1000"
    assert e["first_seen"] == "2026-11-12 10:00:00"
    assert e["array_id"] == ARRAY_ID and e["purity_version"] == "4.6.4"
    assert e["syslog_severity"] is None and e["facility"] is None  # no PRI
    assert e["syslog_time"] == "Nov 12 10:00:00"  # an alert has no time of its own
    assert e["raw"] == ALERT_1000 and e["message"].startswith("CRITICAL Open - fb-a:")


def test_alert_1139_fields_and_pri(syslog):
    e = syslog.parse(ALERT_1139, {}, set())
    assert e["severity"] == "warning" and e["code"] == 1139
    assert e["subject"] == "Message Drop for Remote Syslog (Audit Related)"
    assert e["details"] == "Data-audit messages to syslog server syslog1 were dropped."
    assert e["action"] == "Check the syslog server and the network path."
    assert e["syslog_severity"] == "warning" and e["facility"] == 22
    c = syslog.parse(ALERT_CLOSED, {}, set())
    assert c["state"] == "closed" and c["severity"] == "warning"
    # the Severity field grades the alert, not the leading word
    swapped = ALERT_1139.replace("WARNING Open", "INFO Open")
    assert syslog.parse(swapped, {}, set())["severity"] == "warning"
    # without the field the leading word is used
    lead = ALERT_1139.replace("#012Severity: Warning", "")
    assert syslog.parse(lead, {}, set())["severity"] == "warning"


