def test_file_record_always_passes_the_program_filter(syslog):
    async def go():
        local = asyncio.Queue()
        emit = syslog._emitter(local, {}, set(), [], None)
        assert emit(FILE_FB, "10.21.200.230", "tcp") is True
        assert emit(FILE_FA, "10.21.200.231", "tcp") is True
        assert emit(OS_LINE, "10.21.200.230", "tcp") is False
        assert local.qsize() == 2
        first = local.get_nowait()
        assert list(first) == ["purefb_file_event"]
        assert first["purefb_file_event"]["source"] == "10.21.200.230"
        assert first["purefb_file_event"]["protocol"] == "tcp"

    asyncio.run(go())


def test_other_programs_are_dropped_by_default(syslog):
    e = syslog.parse(OS_LINE, {}, set())
    assert e["kind"] == "other" and e["program"] == "sshd"
    assert e["host"] == "fb-a-fm1" and e["array"] == "fb-a-fm1"
    assert syslog.event_name(e) == "purefb_syslog_other"

    async def go(programs, expect):
        local = asyncio.Queue()
        emit = syslog._emitter(local, {}, set(), [], programs)
        got = [
            emit(OS_LINE, "198.51.100.9", "tcp"),
            emit("garbage", "198.51.100.9", "tcp"),
            emit(AUDIT, "198.51.100.9", "tcp"),
        ]
        assert got == expect, programs
        return local.qsize()

    assert asyncio.run(go(None, [False, False, True])) == 1
    assert asyncio.run(go([], [True, True, True])) == 3
    assert asyncio.run(go(["sshd"], [True, False, False])) == 1
    assert syslog._programs(None) == syslog.DEFAULT_PROGRAMS
    assert syslog._programs("all") == [] and syslog._programs([]) == []
    assert syslog._programs("purity.audit, sshd") == ["purity.audit", "sshd"]


def test_hostname_mapping(syslog):
    # alerts name the array twice (subject line and Array Name field); the
    # map renames that, and the hostname is consulted when the name is not
    # mapped
    assert syslog.parse(ALERT_1000, {"fb-a": "inventory-a"}, set())["array"] == (
        "inventory-a"
    )
    both = {"fb-a": "by-array-name", "fb-a-fm1": "by-host"}
    assert syslog.parse(ALERT_1000, both, set())["array"] == "by-array-name"
    assert syslog.parse(ALERT_1000, {"fb-a-fm1": "by-host"}, set())["array"] == (
        "by-host"
    )
    e = syslog.parse(ALERT_1000, {}, set())
    assert e["array"] == "fb-a" and e["host"] == "fb-a-fm1"
    # a data-audit record is named by its header hostname
    assert syslog.parse(FILE_FB, {"fb-a": "inventory-a"}, set())["array"] == (
        "inventory-a"
    )


